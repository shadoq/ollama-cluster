// benchPrompt is the prompt of the generation test (tg): it asks for a long
// answer so the model does not stop before the requested tokens.
const benchPrompt = "Write a long technical explanation of how a hash map handles collisions, with examples in Go, C and Python."

// The two tests follow llama-bench: pp<N> processes a prompt of N tokens,
// tg<N> generates N tokens. A warm placement is measured several times and
// reported as mean ± standard deviation.

// Placements a benchmark run measures.
const (
	modeHere   = "here"   // this machine alone (cluster_split=false)
	modeSplit  = "split"  // split by the default policy (cluster_split=true)
	modeWorker = "worker" // the worker first: a rule 'worker' for the model while it runs
)

type benchRun struct {
	label    string
	mode     string
	cold     bool
	err      error
	load     time.Duration
	pp       []float64 // prompt processing, tokens/s per repetition
	tg       []float64 // generation, tokens/s per repetition
	ppTokens int       // prompt tokens of the last pp test
	tgTokens int       // tokens generated by the last tg test
	local    uint64
	remote   uint64
	context  int
}

// add merges one more measurement of the same placement.
func (r *benchRun) add(o benchRun) {
	r.pp = append(r.pp, o.pp...)
	r.tg = append(r.tg, o.tg...)
	r.ppTokens, r.tgTokens = o.ppTokens, o.tgTokens
}

// meanStd returns the mean and the sample standard deviation.
func meanStd(xs []float64) (mean, std float64) {
	if len(xs) == 0 {
		return 0, 0
	}
	for _, x := range xs {
		mean += x
	}
	mean /= float64(len(xs))
	if len(xs) < 2 {
		return mean, 0
	}
	for _, x := range xs {
		std += (x - mean) * (x - mean)
	}
	return mean, math.Sqrt(std / float64(len(xs)-1))
}

// formatRate prints a rate like llama-bench: "816.58 ± 10.28".
func formatRate(xs []float64) string {
	if len(xs) == 0 {
		return "-"
	}
	mean, std := meanStd(xs)
	if len(xs) == 1 {
		return fmt.Sprintf("%.2f", mean)
	}
	return fmt.Sprintf("%.2f ± %.2f", mean, std)
}

func benchCmd() *cobra.Command {
	var tokens, promptTokens, repeat, numCtx int
	var yes, asJSON bool
	var only string
	cmd := &cobra.Command{
		Use:   "bench <model>",
		Short: "Measure a model (pp512, tg128) on this machine alone, split, and on the worker first",
		Args:  cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			ctx := cmd.Context()
			model := args[0]
			if tokens < 1 || promptTokens < 16 || repeat < 1 {
				return errors.New("--tokens must be at least 1, --prompt-tokens at least 16 and --repeat at least 1")
			}
			m, err := detectMain(ctx, cmd)
			if err != nil {
				return err
			}
			if m.status == nil {
				return m.statusErr
			}

			var ps api.ProcessResponse
			_ = m.api.do(ctx, http.MethodGet, "/api/ps", nil, &ps)
			for _, p := range ps.Models {
				if sameModel(p.Name, model) && !yes && !confirm(fmt.Sprintf("%s is loaded and may be in use; unload it for the benchmark?", model), false) {
					return errors.New("nothing was changed")
				}
			}

			// with --json stdout carries only the JSON
			var progress io.Writer = os.Stdout
			if asJSON {
				progress = os.Stderr
			}

			modes, err := benchModes(only)
			if err != nil {
				return err
			}
			if len(m.status.Config.ActiveWorkers()) == 0 {
				modes = []string{modeHere}
			}

			// a model larger than this machine never runs here alone: on a
			// shared-memory GPU the attempt would starve the whole machine
			if modes[0] == modeHere {
				var tags api.ListResponse
				_ = m.api.do(ctx, http.MethodGet, "/api/tags", nil, &tags)
				// free memory once the loaded models are unloaded
				var free uint64
				for _, d := range m.status.Devices {
					if !d.Remote {
						free += d.FreeMemory
					}
				}
				for _, l := range m.status.Loaded {
					for _, d := range l.Devices {
						if !d.Remote {
							free += d.Size
						}
					}
				}
				for _, t := range tags.Models {
					if sameModel(t.Name, model) && free > 0 && uint64(t.Size) > free*9/10 {
						fmt.Fprintf(progress, "- this machine alone: skipped, %s does not fit in the %s this machine can free\n", humanBytes(uint64(t.Size)), humanBytes(free))
						modes = modes[1:]
						break
					}
				}
			}

			// from here a stopped benchmark (Ctrl+C, kill) still restores the
			// placement rule and unloads the model
			ctx, stop := signal.NotifyContext(ctx, os.Interrupt, syscall.SIGTERM)
			defer stop()

			// the worker-first runs use a placement rule for this model only;
			// the rule it had before comes back at the end
			if slices.Contains(modes, modeWorker) {
				cfg := m.config()
				prev, had := cfg.Models[model]
				rules := map[string]string{model: cluster.PlaceWorker}
				for k, v := range cfg.Models {
					if k != model {
						rules[k] = v
					}
				}
				cfg.Models = rules
				if err := m.api.saveConfig(ctx, cfg); err != nil {
					return fmt.Errorf("setting the worker rule for the benchmark: %w", err)
				}
				defer func() {
					cfg := m.config()
					delete(cfg.Models, model)
					if had {
						cfg.Models[model] = prev
					}
					if err := m.api.saveConfig(context.WithoutCancel(ctx), cfg); err != nil {
						fmt.Fprintf(os.Stderr, "Warning: could not restore the placement rule of %s: %v (ollama cluster policy model %s auto)\n", model, err, model)
					}
				}()
			}

			b := &bencher{api: m.api, model: model, ppTokens: promptTokens, tgTokens: tokens, numCtx: numCtx}
			var runs []benchRun
			for _, mode := range modes {
				for _, cold := range []bool{true, false} {
					label := map[string]string{modeHere: "this machine", modeSplit: "two machines", modeWorker: "worker first"}[mode]
					n := repeat
					if cold {
						label += ", cold"
						unload(ctx, m.api, model)
						n = 1
					} else {
						label += ", warm"
					}
					fmt.Fprintf(progress, "- %s ...\n", label)
					var r benchRun
					for i := range n {
						one := b.once(ctx, mode)
						if i == 0 {
							r = one
						} else if one.err == nil {
							r.add(one)
						} else {
							r.err = one.err
						}
						if r.err != nil || ctx.Err() != nil {
							break
						}
					}
					if mode == modeWorker && r.err == nil && r.local == 0 {
						label = strings.Replace(label, "worker first", "worker only", 1)
					}
					r.label, r.cold = label, cold
					runs = append(runs, r)
					if r.err != nil {
						fmt.Fprintf(progress, "  %v\n", r.err)
						break
					}
				}
				if ctx.Err() != nil {
					break
				}
			}
			unload(context.WithoutCancel(ctx), m.api, model)

			hw := hardwareLabel(ctx, m)
			if asJSON {
				return printJSON(benchJSON(model, hw, m.status.LlamaCpp, promptTokens, tokens, runs))
			}
			fmt.Printf("\n%s - %s, llama.cpp %s\n", model, hw, m.status.LlamaCpp)
			printBench(os.Stdout, promptTokens, tokens, repeat, runs)
			return nil
		},
	}
	cmd.Flags().IntVar(&tokens, "tokens", 128, "tokens to generate in the generation test (tg)")
	cmd.Flags().IntVar(&promptTokens, "prompt-tokens", 512, "prompt length of the prompt processing test (pp)")
	cmd.Flags().IntVarP(&repeat, "repeat", "r", 3, "repetitions of each warm test")
	cmd.Flags().IntVar(&numCtx, "context", defaultContextLength, "context length (num_ctx) of the runs")
	cmd.Flags().BoolVarP(&yes, "yes", "y", false, "unload the model without asking")
	cmd.Flags().StringVar(&only, "only", "", "placements to run, comma separated: here (or local), split, worker (default: all)")
	cmd.Flags().BoolVar(&asJSON, "json", false, "print the results as JSON on stdout (progress goes to stderr)")
	return cmd
}

func unload(ctx context.Context, a *apiClient, model string) {
	_ = a.do(ctx, http.MethodPost, "/api/generate", map[string]any{"model": model, "keep_alive": 0}, nil)
	// wait until the runner is gone so the next run is really cold
	for range 60 {
		var ps api.ProcessResponse
		if a.do(ctx, http.MethodGet, "/api/ps", nil, &ps) != nil {
			return
		}
		loaded := false
		for _, p := range ps.Models {
			loaded = loaded || sameModel(p.Name, model)
		}
		if !loaded {
			return
		}
		time.Sleep(time.Second)
	}
}

// benchModes parses --only.
func benchModes(only string) ([]string, error) {
	if only == "" {
		return []string{modeHere, modeSplit, modeWorker}, nil
	}
	var modes []string
	for _, m := range strings.Split(only, ",") {
		switch m = strings.TrimSpace(m); m {
		case "local":
			m = modeHere
		case modeHere, modeSplit, modeWorker:
		default:
			return nil, fmt.Errorf("--only: %q is not here, split or worker", m)
		}
		if !slices.Contains(modes, m) {
			modes = append(modes, m)
		}
	}
	// here first: the check whether the model fits here looks at modes[0]
	slices.SortStableFunc(modes, func(a, b string) int {
		return slices.Index([]string{modeHere, modeSplit, modeWorker}, a) - slices.Index([]string{modeHere, modeSplit, modeWorker}, b)
	})
	return modes, nil
}

// bencher runs the two tests of one model.
type bencher struct {
	api      *apiClient
	model    string
	ppTokens int
	tgTokens int
	numCtx   int

	seq  int // makes every pp prompt new, so no cached prefix is reused
	reps int // words in the pp prompt, adjusted to hit ppTokens
}

// ppPrompt returns a raw prompt of about ppTokens tokens. It starts with a
// counter so the runner cannot reuse a cached prefix of an earlier test.
func (b *bencher) ppPrompt() string {
	if b.reps == 0 {
		b.reps = b.ppTokens - 8
	}
	b.seq++
	return fmt.Sprintf("Test %d:%s", b.seq, strings.Repeat(" the", b.reps))
}

func (b *bencher) options(mode string, predict int) map[string]any {
	opts := map[string]any{"num_predict": predict, "num_ctx": b.numCtx, "temperature": 0, "seed": 1}
	switch mode {
	case modeHere:
		opts["cluster_split"] = false
	case modeSplit:
		opts["cluster_split"] = true
	}
	return opts
}

// once runs pp and tg once; the first request of a cold run loads the model.
func (b *bencher) once(ctx context.Context, mode string) benchRun {
	r := benchRun{mode: mode}

	// pp: a raw prompt (no template) and a single generated token
	var pp api.GenerateResponse
	req := map[string]any{"model": b.model, "prompt": b.ppPrompt(), "raw": true, "stream": false, "keep_alive": "10m", "options": b.options(mode, 1)}
	if err := b.api.do(ctx, http.MethodPost, "/api/generate", req, &pp); err != nil {
		r.err = err
		return r
	}
	r.load = pp.LoadDuration
	r.ppTokens = pp.PromptEvalCount
	if pp.PromptEvalDuration > 0 {
		r.pp = []float64{float64(pp.PromptEvalCount) / pp.PromptEvalDuration.Seconds()}
	}
	if pp.PromptEvalCount > 0 {
		b.reps = max(1, b.reps+b.ppTokens-pp.PromptEvalCount)
	}

	// tg: a short prompt that asks for a long answer
	var tg api.GenerateResponse
	req = map[string]any{"model": b.model, "prompt": benchPrompt, "stream": false, "think": false, "keep_alive": "10m", "options": b.options(mode, b.tgTokens)}
	err := b.api.do(ctx, http.MethodPost, "/api/generate", req, &tg)
	// models with no thinking switch reject think=false
	if err != nil && strings.Contains(err.Error(), "think") {
		delete(req, "think")
		err = b.api.do(ctx, http.MethodPost, "/api/generate", req, &tg)
	}
	if err != nil {
		r.err = err
		return r
	}
	r.tgTokens = tg.EvalCount
	if tg.EvalDuration > 0 {
		r.tg = []float64{float64(tg.EvalCount) / tg.EvalDuration.Seconds()}
	}

	if st, err := b.api.status(ctx); err == nil {
		for _, l := range st.Loaded {
			if !sameModel(l.Model, b.model) {
				continue
			}
			r.context = l.Context
			for _, d := range l.Devices {
				if d.Remote {
					r.remote += d.Size
				} else {
					r.local += d.Size
				}
			}
		}
	}
	if mode != modeHere && r.remote == 0 {
		r.err = errors.New("the model loaded on this machine only (worker not usable or busy; see 'ollama cluster status')")
	}
	return r
}

// printBench prints the runs as a table with llama-bench test names.
func printBench(w io.Writer, ppTokens, tgTokens, repeat int, runs []benchRun) {
	pp, tg := fmt.Sprintf("pp%d t/s", ppTokens), fmt.Sprintf("tg%d t/s", tgTokens)
	fmt.Fprintf(w, "%-22s %10s %18s %18s  %s\n", "", "load", pp, tg, "memory")
	var notes []string
	for _, r := range runs {
		if r.err != nil {
			fmt.Fprintf(w, "%-22s %s\n", r.label, firstLine(r.err.Error()))
			continue
		}
		mem := humanBytes(r.local) + " here"
		if r.remote > 0 {
			mem += " + " + humanBytes(r.remote) + " worker"
		}
		load := "-"
		if r.cold {
			load = humanDuration(r.load)
		}
		fmt.Fprintf(w, "%-22s %10s %18s %18s  %s, context %d\n", r.label, load, formatRate(r.pp), formatRate(r.tg), mem, r.context)
		if r.ppTokens > 0 && r.ppTokens != ppTokens {
			notes = append(notes, fmt.Sprintf("%s: the prompt had %d tokens", r.label, r.ppTokens))
		}
		if r.tgTokens > 0 && r.tgTokens < tgTokens {
			notes = append(notes, fmt.Sprintf("%s: the model stopped after %d tokens", r.label, r.tgTokens))
		}
	}
	fmt.Fprintf(w, "cold: one run that includes loading the model; warm: mean ± standard deviation of %d runs\n", repeat)
	for _, n := range notes {
		fmt.Fprintf(w, "note: %s\n", n)
	}
}

// hardwareLabel names the machines for the result, e.g.
// "2 x NVIDIA GB10 (gx10-8c60 + gx10-bf3f)".
func hardwareLabel(ctx context.Context, m *mainOllama) string {
	name, _, _ := localGPU(ctx)
	if name == "" {
		name = "this machine"
	}
	n := 1
	var workers []string
	for _, c := range m.status.Workers {
		if c.Usable {
			n++
			workers = append(workers, c.Worker.Label())
		}
	}
	if n == 1 {
		return name
	}
	return fmt.Sprintf("%d x %s (this machine + %s)", n, name, strings.Join(workers, ", "))
}

func firstLine(s string) string {
	line, _, _ := strings.Cut(s, "\n")
	return line
}

type benchResult struct {
	Model        string           `json:"model"`
	Hardware     string           `json:"hardware"`
	LlamaCpp     string           `json:"llama_cpp"`
	PromptTokens int              `json:"prompt_tokens"`
	Tokens       int              `json:"tokens"`
	Runs         []benchRunResult `json:"runs"`
}

type benchRunResult struct {
	Label     string  `json:"label"`
	Mode      string  `json:"mode"`
	Split     bool    `json:"split"`
	Cold      bool    `json:"cold"`
	Error     string  `json:"error,omitempty"`
	LoadSec   float64 `json:"load_seconds,omitempty"`
	Samples   int     `json:"samples,omitempty"`
	PromptTPS float64 `json:"prompt_tok_s,omitempty"` // pp, mean
	PromptStd float64 `json:"prompt_tok_s_std,omitempty"`
	PromptTok int     `json:"prompt_tokens,omitempty"`
	GenTPS    float64 `json:"gen_tok_s,omitempty"` // tg, mean
	GenStd    float64 `json:"gen_tok_s_std,omitempty"`
	GenTokens int     `json:"gen_tokens,omitempty"`
	Local     uint64  `json:"memory_here,omitempty"`
	Remote    uint64  `json:"memory_worker,omitempty"`
	Context   int     `json:"context,omitempty"`
}

func benchJSON(model, hw, llamaCpp string, ppTokens, tokens int, runs []benchRun) benchResult {
	res := benchResult{Model: model, Hardware: hw, LlamaCpp: llamaCpp, PromptTokens: ppTokens, Tokens: tokens, Runs: []benchRunResult{}}
	for _, r := range runs {
		out := benchRunResult{Label: r.label, Mode: r.mode, Split: r.mode != modeHere, Cold: r.cold, Samples: len(r.tg), PromptTok: r.ppTokens, GenTokens: r.tgTokens, Local: r.local, Remote: r.remote, Context: r.context}
		out.PromptTPS, out.PromptStd = meanStd(r.pp)
		out.GenTPS, out.GenStd = meanStd(r.tg)
		if r.cold {
			out.LoadSec = r.load.Seconds()
		}
		if r.err != nil {
			out.Error = firstLine(r.err.Error())
		}
		res.Runs = append(res.Runs, out)
	}
	return res
}
